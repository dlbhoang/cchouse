const address = (
  id: number,
  displayAddress: string,
  lat?: number,
  lng?: number,
  propTypeName = "Nhà phố",
) =>
  (() => {
    const addressParts = displayAddress.split(",").map((part) => part.trim());
    const firstLine = addressParts[0] ?? "";
    const houseNumber = firstLine.match(/^\d+[\w/-]*/)?.[0] ?? "";
    return {
    Id: id,
    PropName: displayAddress,
    DisplayAddress: displayAddress,
    AddressNumber: houseNumber,
    SubAddressName: "",
    StreetName: firstLine.slice(houseNumber.length).trim(),
    ProvinceName: "Thành phố Hồ Chí Minh",
    DistrictName: addressParts.find((part) => /Quận|Tân Bình/.test(part)) ?? "Quận 3",
    WardName: addressParts.find((part) => part.startsWith("Phường")) ?? "",
    PropTypeName: propTypeName,
    StatusUsageName: "Đất ở đô thị",
    DirectionName: "Đông Nam",
    LocationName: "Mặt tiền",
    LocationFeatureName: "Khu dân cư hiện hữu",
    DisplayLaws: ["Sổ hồng riêng"],
    StreetWidth: 8,
    DistanceToFont: 0,
    AlleyTurns: 0,
    LengthLegal: 20,
    WidthLegal: 5,
    AreaLegal: 100,
    BackSideLegal: 5,
    Errors: "",
    LocationFeature: 1,
    IsOneWay: false,
    UsageLaw: 1,
    OldAddressNumber: "",
    OldDistrictId: null,
    OldWardId: null,
    OldStreetId: null,
    Lat: lat,
    Lng: lng,
    } as IPropResponse["PropAddress"];
  })();

